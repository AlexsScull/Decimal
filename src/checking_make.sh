echo -e "\033[1;32m🔍 make cppcheck\033[0m"
make cppcheck
echo -e "\033[1;34m----------------------------------------\033[0m"

# Проверка утечек памяти с Valgrind (только Linux)
echo -e "\033[1;32m💧 make valgrind\033[0m"
make valgrind
