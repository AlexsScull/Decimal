#!/bin/bash

echo -e "\033[1;34m🚀 Запуск всех тестов и проверок...\033[0m"
echo -e "\033[1;34m========================================\033[0m"

# Стандартная сборка
echo -e "\033[1;32m📦 make s21_decimal.a\033[0m"
make clean
make s21_decimal.a
echo -e "\033[1;34m----------------------------------------\033[0m"

# Стандартная сборка
echo -e "\033[1;32m📦 make all\033[0m"
make clean
make all
echo -e "\033[1;34m----------------------------------------\033[0m"

# Сборка с пересозданием всех файлов
echo -e "\033[1;32m🔄 make rebuild\033[0m"
make rebuild
echo -e "\033[1;34m----------------------------------------\033[0m"

# Сборка всех тестов
echo -e "\033[1;32m🧪 make test\033[0m"
make clean
make test
echo -e "\033[1;34m----------------------------------------\033[0m"

